#!/usr/bin/env python3
"""Generate the bounded 0709:0C3F clock from the identical 08AE clock template.

Requires the owner START.EXE. --check compares generated output without writing.
"""
import hashlib
import sys
from pathlib import Path
from resident_loader_map import unpack
from emit_raw_cpu_c import Emitter

root = Path(__file__).resolve().parents[2]
img = bytes(unpack((root / 'resources/DOS/POOLRAD/START.EXE').read_bytes())[0])
body = img[0x7090 + 0x0c3f:0x7090 + 0x0cab]
assert hashlib.sha256(body).hexdigest() == 'a8e33767ba204b74a7c909cb85a7580ddbbaa36d60dfafb5fb3425d8c16412ed'
assert body == img[0x8ae0:0x8ae0 + 0x6c]
e = Emitter(body, 0x0c3f, 0x0cab, {0x00a2: 'call_gettime', 0x0a5b: 'call_longmul'})
template = (root / 'src/recovered/resident_08ae_time_0000_cpu.c').read_text()
prefix = template.split('    for (;;) {', 1)[0]
prefix = prefix.replace('/* START.EXE resident 08AE:0000 time in hundredths, raw CPU (docs/re/RES_08AE_TIME_0000_CPU.md).',
                        '/* START.EXE resident 0709:0C3F clock; generated by emit_res0709_time_0c3f.py.')
prefix = prefix.replace('#include "poolrad/recovered/resident_08ae_time_0000_cpu.h"',
                        '#include "poolrad/recovered/resident_0709_time_0c3f_cpu.h"')
prefix = prefix.replace('pr_r08ae_time_0000_cpu(', 'pr_r0709_time_0c3f_cpu(')
prefix = prefix.replace(
    '    return (uint16_t)(pr_bus_read8(b, at) | ((uint16_t)pr_bus_read8(b, (at + 1u) & MASK) << 8u));',
    '    uint8_t lo = pr_bus_read8(b, at);\n    uint8_t hi = pr_bus_read8(b, (at + 1u) & MASK);\n    return (uint16_t)(lo | ((uint16_t)hi << 8u));')
prefix = prefix.replace('b->ega != NULL || ', '')
prefix = prefix.replace('c->ip != 0x0000u)', 'c->ip != 0x0C3Fu || !safe_stack(b, c))')
marker = 'pr_r08ae_time_cpu_status pr_r0709_time_0c3f_cpu('
guard = '''/* The flat-RAM leaves may touch the whole constructed frame, including the
 * caller return. Reject both bytes of every potentially addressed word when
 * EGA is attached. The DOS service contract forbids RAM writes. */
static int safe_stack(const pr_bus *b, const pr_cpu_t *c)
{
    int delta;
    if (b->ega == NULL) return 1;
    for (delta = -0x2e; delta <= 3; ++delta) {
        size_t at = physical(c->ss, (uint16_t)(c->sp + delta));
        size_t next = (at + 1u) & MASK;
        if ((at >= 0xA0000u && at < 0xB0000u) ||
            (next >= 0xA0000u && next < 0xB0000u)) return 0;
    }
    return 1;
}
'''
prefix = prefix.replace(marker, guard + marker)
source = prefix + '    for (;;) {\n        switch (c->ip) {\n' + '\n'.join(e.cases()) + '\n        default: return STATUS(TRANSFER);\n        }\n    }\n}\n'
target = root / 'src/recovered/resident_0709_time_0c3f_cpu.c'
if '--check' in sys.argv:
    if target.read_text() != source:
        raise SystemExit('generated source differs')
else:
    target.write_text(source)
print('0709 clock cases:', len(e.ins))
