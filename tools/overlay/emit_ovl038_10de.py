#!/usr/bin/env python3
"""Regenerate src/recovered/overlay_u38_10de_cpu.c and its header with emit_raw_cpu_c.py.

python3 tools/overlay/emit_ovl038_10de.py [--check]   (--check compares instead of writing)
Needs the owner START.EXE and GAME.OVR under resources/ (read only; nothing is executed). Prints the undefined-flag
observability report (empty for this body: no SHL/SHR/MUL).
The emitted body runs on flat RAM (the 009E dispatcher's handler convention): its rd8/wr8/rd16/wr16 take the RAM pointer.

Three call sites are not generated by the shared emitter and are written here:
  +10FA CALL +001F (after PUSH CS at +10F9): composes the credited gated append pr_u38_gated_append_001f_cpu at CS:001F.
  +1126 LCALL 00BA:16EC: RES_00BA_16EC is recorded as not closable; the body stops PENDING before the call.
  +115D LCALL 00B0:0052: the loaded stub of unit 9E entry 10 must be EAh 52 0E (a far JMP to +0E52, the credited list
         append), checked before anything is pushed (CODE otherwise), then the far transfer composes
         pr_u9e_list_append_0e52_cpu at the stub's segment.
The other two, +111B LCALL 0AF8:0B0B (StrLoad) and +1142 LCALL 00BA:2199 (the credited sidecar lookup), are the emitter's
standard far calls composed through their handlers."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from overlay_inventory import find_units, parse_mz
from emit_raw_cpu_c import Emitter

ROOT = Path(__file__).resolve().parents[2]
exe = (ROOT / 'resources/DOS/POOLRAD/START.EXE').read_bytes()
ovr = (ROOT / 'resources/DOS/POOLRAD/GAME.OVR').read_bytes()
unit = {u['stub_para']: u for u in find_units(exe[parse_mz(exe)['header_bytes']:], ovr)}[0x38]
code = ovr[unit['ovr_offset']:unit['ovr_offset'] + unit['code_size']]
START, END = 0x10DE, 0x1168
assert unit['entries'][37] == START and unit['entries'][38] == END, 'unit 38h public entry 37 is +10DE and entry 38 starts at +1168'
assert all(fx in unit['fixups'] for fx in (0x111E, 0x1129, 0x1145, 0x1160)), 'the four far-call segment words are loader fixups'


def stub_hop(site, nx, stub_off, entry, handler):
    """A far call through a loaded overlay stub: the stub's five bytes are checked before anything is pushed."""
    return (f'{{uint16_t st=rd16(b,c->cs,0x{site + 3:04X}u);'
            f'if(rd8(b,st,0x{stub_off:04X}u)!=0xEAu||rd16(b,st,0x{stub_off + 1:04X}u)!=0x{entry:04X}u)'
            f'{{dg->diag->site=0x{site:04X}u;return STATUS(CODE);}}'
            f'push(b,c,c->cs);push(b,c,0x{nx:04X}u);c->cs=rd16(b,st,0x{stub_off + 3:04X}u);c->ip=0x{entry:04X}u;'
            f'{{int s={handler}(b,c,dg);if(s)return (pr_status_t)s;}}'
            f'if(c->cs!=caller||c->ip!=0x{nx:04X}u)return STATUS(TRANSFER);}}')


class HandlerEmitter(Emitter):
    def case(self, i):
        a, nx = i.address, self.next[i.address]
        if i.mnemonic == 'call':
            assert a == 0x10FA and i.op_str == '0x1f', f'unexpected near call at {a:04X}'
            return (f'push(b,c,0x{nx:04X}u);c->ip=0x001Fu;'
                    f'{{int s=call_gated_append_001f(b,c,dg);if(s)return (pr_status_t)s;}}'
                    f'if(c->cs!=caller||c->ip!=0x{nx:04X}u)return STATUS(TRANSFER);')
        if i.mnemonic == 'lcall' and a == 0x1126:
            assert i.op_str == '0xba, 0x16ec'
            return 'dg->diag->site=0x1126u;dg->diag->callee=3;return STATUS(PENDING);'
        if i.mnemonic == 'lcall' and a == 0x115D:
            assert i.op_str == '0xb0, 0x52'
            return stub_hop(a, nx, 0x0052, 0x0E52, 'call_u9e_list_append_0e52')
        return super().case(i)


e = HandlerEmitter(code[START:END], START, END, {0x0B0B: 'call_strload_0b0b', 0x2199: 'call_sidecar_lookup_2199'})
assert len(e.ins) == 60, 'the span decodes to 60 instructions'
assert [i.address for i in e.ins if i.mnemonic in ('call', 'lcall')] == [0x10FA, 0x111B, 0x1126, 0x1142, 0x115D], 'five calls'
for a, mn, ops, und, vis in e.undefined_report():
    print(f'UNDEF {a:04X} {mn} {ops}: {und} -> {vis if vis else "never observed (overwritten on every path)"}')
cases = '\n'.join(e.cases())

