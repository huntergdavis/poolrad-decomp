#!/usr/bin/env python3
"""Regenerate src/recovered/overlay_u38_0c4b_cpu.c and its header with emit_raw_cpu_c.py.

python3 tools/overlay/emit_ovl038_0c4b.py [--check]   (--check compares instead of writing)
Needs the owner START.EXE and GAME.OVR under resources/ (read only; nothing is executed). Prints the undefined-flag
observability report: the one producer is SHL AX,1 at +0C9D (AF), and it is visible at the RETF (nothing overwrites
FLAGS after it); the helper applies the pinned DOSBox-X rule AF := 1 for a non-zero count.
The emitted body runs on flat RAM (the 009E dispatcher's handler convention): its rd8/wr8/rd16/wr16 take the RAM pointer.

One call site is not generated by the shared emitter and is written here:
  +0C8C LCALL 00BA:16EC: RES_00BA_16EC is recorded as not closable; the body stops PENDING before the call.
The other call, +0C81 LCALL 0AF8:0B0B (SYSTEM StrLoad), is the emitter's standard far call composed through its handler."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from overlay_inventory import find_units, parse_mz
from emit_raw_cpu_c import Emitter

ROOT = Path(__file__).resolve().parents[2]
exe = (ROOT / 'resources/DOS/POOLRAD/START.EXE').read_bytes()
ovr = (ROOT / 'resources/DOS/POOLRAD/GAME.OVR').read_bytes()
unit = {u['stub_para']: u for u in find_units(exe[parse_mz(exe)['header_bytes']:], ovr)}[0x38]
code = ovr[unit['ovr_offset']:unit['ovr_offset'] + unit['code_size']]
START, END = 0x0C4B, 0x0CA8
assert unit['entries'][33] == START and unit['entries'][34] == 0x0CC3, 'unit 38h public entry 33 is +0C4B and entry 34 starts at +0CC3'
assert code[END] == 26 and END + 27 == 0x0CC3, 'the 27 bytes after the RETF are entry 34\'s Pascal string, not code'
assert all(fx in unit['fixups'] for fx in (0x0C84, 0x0C8F)), 'the two far-call segment words are loader fixups'


class HandlerEmitter(Emitter):
    def case(self, i):
        a = i.address
        if i.mnemonic == 'lcall' and a == 0x0C8C:
            assert i.op_str == '0xba, 0x16ec'
            return 'dg->diag->site=0x0C8Cu;dg->diag->callee=2;return STATUS(PENDING);'
        assert i.mnemonic != 'call', f'unexpected near call at {a:04X}'
        return super().case(i)


e = HandlerEmitter(code[START:END], START, END, {0x0B0B: 'call_strload_0b0b'})
assert len(e.ins) == 37, 'the span decodes to 37 instructions'
assert [i.address for i in e.ins if i.mnemonic == 'lcall'] == [0x0C81, 0x0C8C], 'two far calls'
for a, mn, ops, und, vis in e.undefined_report():
    print(f'UNDEF {a:04X} {mn} {ops}: {und} -> {vis if vis else "never observed (overwritten on every path)"}')
cases = '\n'.join(e.cases())

header = '''#ifndef POOLRAD_RECOVERED_OVERLAY_U38_0C4B_CPU_H
#define POOLRAD_RECOVERED_OVERLAY_U38_0C4B_CPU_H
#include <stddef.h>
#include <stdint.h>
#include "poolrad/recovered/system_string_leaves_cpu.h"

/* Raw-CPU, full-state model of GAME.OVR unit 38h +[0C4B,0CA8) (93 bytes, 37 instructions, RETF 0Ah), the handler that
 * the 009E dispatcher reaches through slot 39 (public entry 33, stub 0041:00C5). It is a PARTIAL CHAIN: the resident
 * window message RES_00BA_16EC is recorded as not closable, and the body stops before its call. Nothing is skipped or
 * treated as a success.
 * Arguments (after the far call: [SP] IP, [SP+2] CS): [BP+6] a word, unused by this body; [BP+8] a far pointer A (a record
 * whose byte +3 holds flag bits); [BP+0Ch] a far pointer B (a record whose word +30h is a counter). Locals (SUB SP,6):
 * [BP-5] a 5-byte string buffer ([BP-6] is never touched).
 *   1. AL := A+3 AND 10h (AND, then OR AL,AL): nonzero jumps to step 3.
 *   2. A+3 := A+3 + 10h (XOR AH,AH; ADD AX,10h; the byte store; bit 4 was clear, so no carry leaves the byte). Push B and
 *      SS:BP-5; push CS:0C46; 0AF8:0B0B (SYSTEM StrLoad) copies the 4-character string at CS:0C46 into the buffer and pops
 *      only its source (RETF 4); push AX = AH:0Ah and AX = AH:01h (AH is whatever StrLoad left); then +0C8C LCALL
 *      00BA:16EC: the model stops PENDING at +0C8C with the six argument words (B, the buffer pointer, 0Ah, 1) pushed and
 *      nothing pushed for the call. 16EC's effects (RETF 0Ch) and the following INC word B+30h are NOT completed paths on
 *      this branch: step 3 is reached by the model only through the jump of step 1.
 *   3. DS:681A := the low byte of (zero-extended DS:681A) SHL 1 (the byte doubles, its top bit falls into AH and is lost);
 *      MOV SP,BP; POP BP; RETF 0Ah.
 * Every far pointer is reread from the frame at each use (LES at each use). CS is the unit's load segment; the far-call
 * segment words CS:0C84 and CS:0C8F are loader fixups, read live. Flat 1 MiB A20-off RAM: offsets wrap at 16 bits,
 * physical addresses at 1 MiB, word operands are physically contiguous. Flags follow every flag-setting instruction
 * (SUB SP; AND/OR/XOR logic; ADD AX,10h; INC word keeps CF; SHL AX,1: CF = old bit 15, OF = MSB(result) ^ CF, SZP of the
 * result, AF := 1 by the pinned DOSBox-X rule, and that AF is visible at the RETF of step 3). See
 * docs/re/OVL_0038_0C4B_CPU.md for the contract and evidence. */
typedef struct {
    uint16_t ax, bx, cx, dx, si, di;
    uint16_t bp, sp, cs, ip, ds, es, ss, flags;
} pr_u38_0c4b_cpu;

typedef enum {
    PR_U38_0C4B_OK = 0,         /* RETF 0Ah executed (only through the step-1 jump: A+3 bit 4 already set) */
    PR_U38_0C4B_ARGUMENT,       /* null RAM or CPU, RAM not 1 MiB, IP not 0C4Bh; nothing changed */
    PR_U38_0C4B_CALLEE,         /* StrLoad did not return (diagnostic.callee_status); state as it left it */
    PR_U38_0C4B_TRANSFER,       /* StrLoad returned somewhere other than the instruction after its call */
    PR_U38_0C4B_PENDING         /* +0C8C LCALL 00BA:16EC reached (RES_00BA_16EC not closable); IP 0C8C, six words pushed */
} pr_u38_0c4b_status;

typedef struct {
    int callee;                     /* -1 none; 1 = StrLoad 0AF8:0B0B, 2 = 16EC (PENDING) */
    int callee_status;              /* the last callee's own status (-1 when none ran) */
    uint16_t site;                  /* the call site of the last callee or stop (0 when none) */
} pr_u38_0c4b_diagnostic;

/* diagnostic may be NULL. */
pr_u38_0c4b_status pr_u38_handler_0c4b_cpu(uint8_t *ram, size_t ram_size, pr_u38_0c4b_cpu *cpu,
                                           pr_u38_0c4b_diagnostic *diagnostic);
#endif
'''

source = '''/* GAME.OVR unit 38h +0C4B (009E slot 39), raw CPU on flat RAM (docs/re/OVL_0038_0C4B_CPU.md).
 * One case per original instruction; operands are reread from RAM in source order. Generated by
 * tools/overlay/emit_ovl038_0c4b.py; the +0C8C stop is that script's one hand-written case. */
#include "poolrad/recovered/overlay_u38_0c4b_cpu.h"
#include <string.h>
#define RAM_SIZE ((size_t)1u << 20)
#define MASK (RAM_SIZE - 1u)
#define STATUS(s) PR_U38_0C4B_##s
typedef pr_u38_0c4b_status pr_status_t;
typedef pr_u38_0c4b_cpu pr_cpu_t;
typedef struct {
    pr_u38_0c4b_diagnostic *diag;
} pr_run;
_Static_assert(sizeof(pr_cpu_t) == sizeof(pr_system_leaf_cpu), "CPU layout (SYSTEM leaf)");
static size_t physical(uint16_t seg, uint16_t off) { return (((size_t)seg << 4u) + off) & MASK; }
static uint16_t word_at(uint8_t *b, size_t at) { return (uint16_t)(b[at] | ((uint16_t)b[(at + 1u) & MASK] << 8u)); }
static uint8_t rd8(uint8_t *b, uint16_t seg, uint16_t off) { return b[physical(seg, off)]; }
static uint16_t rd16(uint8_t *b, uint16_t seg, uint16_t off) { return word_at(b, physical(seg, off)); }
static void wr8(uint8_t *b, uint16_t seg, uint16_t off, uint8_t v) { b[physical(seg, off)] = v; }
static void wr16(uint8_t *b, uint16_t seg, uint16_t off, uint16_t v)
{
    size_t at = physical(seg, off);
    b[at] = (uint8_t)v; b[(at + 1u) & MASK] = (uint8_t)(v >> 8u);
}
static void push(uint8_t *b, pr_cpu_t *c, uint16_t v) { c->sp = (uint16_t)(c->sp - 2u); wr16(b, c->ss, c->sp, v); }
static uint16_t pop(uint8_t *b, pr_cpu_t *c) { uint16_t v = rd16(b, c->ss, c->sp); c->sp = (uint16_t)(c->sp + 2u); return v; }
static void szp(pr_cpu_t *c, uint16_t r, unsigned bits)
{
    uint8_t p = (uint8_t)r;
    p ^= (uint8_t)(p >> 4u); p ^= (uint8_t)(p >> 2u); p ^= (uint8_t)(p >> 1u);
    if ((p & 1u) == 0u) c->flags |= 0x04u;
    if ((r & (bits == 8u ? 0xFFu : 0xFFFFu)) == 0u) c->flags |= 0x40u;
    if (r & (bits == 8u ? 0x80u : 0x8000u)) c->flags |= 0x80u;
}
static uint16_t arith(pr_cpu_t *c, uint16_t l, uint16_t r, unsigned carry, unsigned bits, unsigned sub)
{
    uint32_t mask = bits == 8u ? 0xFFu : 0xFFFFu, sign = bits == 8u ? 0x80u : 0x8000u;
    uint32_t wide = sub ? (uint32_t)l - r - carry : (uint32_t)l + r + carry;
    uint16_t res = (uint16_t)(wide & mask);
    c->flags &= (uint16_t)~0x08D5u;
    if (sub ? (uint32_t)l < (uint32_t)r + carry : wide > mask) c->flags |= 1u;
    if ((l ^ r ^ res) & 0x10u) c->flags |= 0x10u;
    if ((sub ? (l ^ r) & (l ^ res) : (uint16_t)~(l ^ r) & (l ^ res)) & sign) c->flags |= 0x800u;
    szp(c, res, bits); return res;
}
static uint16_t incdec(pr_cpu_t *c, uint16_t v, unsigned bits, unsigned dec)
{
    uint16_t cf = c->flags & 1u; v = arith(c, v, 1u, 0u, bits, dec);
    c->flags = (uint16_t)((c->flags & ~1u) | cf); return v;
}
static uint16_t logic(pr_cpu_t *c, uint16_t v, unsigned bits)
{
    v = (uint16_t)(v & (bits == 8u ? 0xFFu : 0xFFFFu)); c->flags &= (uint16_t)~0x08D5u; szp(c, v, bits); return v;
}
/* SHL/SHR by a count: CF = the last bit shifted out, OF = (pre ^ res) & sign (MSB(result) ^ CF for SHL; the operand's MSB
 * for SHR count 1, as pinned t_SHRw); AF := 1 (pinned DOSBox-X; Unicorn clears it). This body's SHL AX,1 at +0C9D is the
 * last flag writer before its RETF, so that AF is visible to the caller. */
static uint16_t shift(pr_cpu_t *c, uint16_t v, uint8_t n, unsigned bits, unsigned right)
{
    uint32_t mask = bits == 8u ? 0xFFu : 0xFFFFu, sign = bits == 8u ? 0x80u : 0x8000u, pre, res;
    n &= 0x1Fu;
    if (n == 0u) return v;
    v = (uint16_t)(v & mask);
    pre = right ? ((uint32_t)v >> (n - 1u)) : (((uint32_t)v << (n - 1u)) & mask);
    res = right ? (pre >> 1u) : ((pre << 1u) & mask);
    c->flags &= (uint16_t)~0x08D5u;
    c->flags |= 0x10u; /* pinned: AF = (count & 1Fh) != 0 */
    if (right ? (pre & 1u) : (pre & sign)) c->flags |= 1u;
    if ((pre ^ res) & sign) c->flags |= 0x800u;
    szp(c, (uint16_t)res, bits); return (uint16_t)res;
}
/* 0AF8:0B0B, SYSTEM StrLoad (string copy), on the same RAM. */
static int call_strload_0b0b(uint8_t *b, pr_cpu_t *c, pr_run *r)
{
    pr_system_leaf_cpu in; int s;
    memcpy(&in, c, sizeof in);
    s = (int)pr_system_strload_0b0b(b, RAM_SIZE, &in);
    memcpy(c, &in, sizeof in);
    r->diag->callee = 1; r->diag->callee_status = s; r->diag->site = 0x0C81u;
    return s == PR_SYSTEM_LEAF_RETURNED ? 0 : STATUS(CALLEE);
}

pr_u38_0c4b_status pr_u38_handler_0c4b_cpu(uint8_t *b, size_t ram_size, pr_u38_0c4b_cpu *c,
                                           pr_u38_0c4b_diagnostic *diagnostic)
{
    pr_run run, *dg = &run;
    pr_u38_0c4b_diagnostic local;
    uint16_t caller;
    if (b == NULL || c == NULL || ram_size != RAM_SIZE || c->ip != 0x0C4Bu)
        return STATUS(ARGUMENT);
    run.diag = diagnostic != NULL ? diagnostic : &local;
    memset(run.diag, 0, sizeof *run.diag);
    run.diag->callee = -1; run.diag->callee_status = -1;
    caller = c->cs;
    for (;;) {
        switch (c->ip) {
CASES
        default: return STATUS(TRANSFER);
        }
    }
}
'''.replace('CASES', cases)
targets = {ROOT / 'include/poolrad/recovered/overlay_u38_0c4b_cpu.h': header,
           ROOT / 'src/recovered/overlay_u38_0c4b_cpu.c': source}
if '--check' in sys.argv:
    bad = [str(p) for p, text in targets.items() if p.read_text() != text]
    print('EMIT_CHECK', 'MISMATCH ' + ', '.join(bad) if bad else 'OK'); sys.exit(1 if bad else 0)
for p, text in targets.items():
    p.write_text(text)
print('cases', len(e.ins))
