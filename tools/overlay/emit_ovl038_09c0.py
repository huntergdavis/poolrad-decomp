#!/usr/bin/env python3
"""Regenerate src/recovered/overlay_u38_handler_09c0_cpu.c and its header with emit_raw_cpu_c.py.

python3 tools/overlay/emit_ovl038_09c0.py [--check]   (--check compares instead of writing)
Needs the owner START.EXE and GAME.OVR under resources/ (read only; nothing is executed). Prints the undefined-flag
observability report (empty for this body: no SHL/SHR/MUL).
The emitted body runs on flat RAM (the 009E dispatcher's handler convention): its rd8/wr8/rd16/wr16 take the RAM pointer.

Four call sites are not generated by the shared emitter and are written here:
  +09D4 LCALL 00B0:0048: the loaded stub of unit 9E entry 8 must be EAh E3 0D (a far JMP to +0DE3, the credited roll), checked
         before anything is pushed (CODE otherwise), then the far transfer composes pr_u9e_entry8_fullstate_compose_0de3.
  +09EF CALL +0000 (after PUSH CS at +09EE): composes the credited helper pr_u38_helper_0000_cpu at CS:0000.
  +0A0D LCALL 00BA:16EC: RES_00BA_16EC is recorded as not closable; the body stops PENDING before the call.
  +0A32 LCALL 00B0:002A: the loaded stub of unit 9E entry 2 must be EAh 26 00 (+0026), checked before anything is pushed
         (CODE otherwise), then the far transfer composes pr_u9e_list_release_0026_cpu at the stub's segment."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from overlay_inventory import find_units, parse_mz
from emit_raw_cpu_c import Emitter

ROOT = Path(__file__).resolve().parents[2]
exe = (ROOT / 'resources/DOS/POOLRAD/START.EXE').read_bytes()
ovr = (ROOT / 'resources/DOS/POOLRAD/GAME.OVR').read_bytes()
unit = {u['stub_para']: u for u in find_units(exe[parse_mz(exe)['header_bytes']:], ovr)}[0x38]
code = ovr[unit['ovr_offset']:unit['ovr_offset'] + unit['code_size']]
START, END = 0x09C0, 0x0A3D
assert unit['entries'][24] == START and unit['entries'][25] == END, 'unit 38h public entry 24 is +09C0 and entry 25 starts at +0A3D'
assert all(fx in unit['fixups'] for fx in (0x09D7, 0x0A05, 0x0A10, 0x0A35)), 'the four far-call segment words are loader fixups'


def stub_hop(site, nx, stub_off, entry, handler):
    """A far call through a loaded overlay stub: the stub's five bytes are checked before anything is pushed."""
    return (f'{{uint16_t st=rd16(b,c->cs,0x{site + 3:04X}u);'
            f'if(rd8(b,st,0x{stub_off:04X}u)!=0xEAu||rd16(b,st,0x{stub_off + 1:04X}u)!=0x{entry:04X}u)'
            f'{{dg->diag->site=0x{site:04X}u;return STATUS(CODE);}}'
            f'push(b,c,c->cs);push(b,c,0x{nx:04X}u);c->cs=rd16(b,st,0x{stub_off + 3:04X}u);c->ip=0x{entry:04X}u;'
            f'{{int s={handler}(b,c,dg);if(s)return (pr_status_t)s;}}'
            f'if(c->cs!=caller||c->ip!=0x{nx:04X}u)return STATUS(TRANSFER);}}')


class HandlerEmitter(Emitter):
    def case(self, i):
        a, nx = i.address, self.next[i.address]
        if i.mnemonic == 'call':
            assert a == 0x09EF and i.op_str == '0', f'unexpected near call at {a:04X}'
            return (f'push(b,c,0x{nx:04X}u);c->ip=0x0000u;'
                    f'{{int s=call_helper_0000(b,c,dg);if(s)return (pr_status_t)s;}}'
                    f'if(c->cs!=caller||c->ip!=0x{nx:04X}u)return STATUS(TRANSFER);')
        if i.mnemonic == 'lcall' and a == 0x09D4:
            assert i.op_str == '0xb0, 0x48'
            return stub_hop(a, nx, 0x0048, 0x0DE3, 'call_u9e_roll_0de3')
        if i.mnemonic == 'lcall' and a == 0x0A0D:
            assert i.op_str == '0xba, 0x16ec'
            return 'dg->diag->site=0x0A0Du;dg->diag->callee=4;return STATUS(PENDING);'
        if i.mnemonic == 'lcall' and a == 0x0A32:
            assert i.op_str == '0xb0, 0x2a'
            return stub_hop(a, nx, 0x002A, 0x0026, 'call_u9e_list_release_0026')
        return super().case(i)


e = HandlerEmitter(code[START:END], START, END, {0x0B0B: 'call_strload_0b0b'})
assert len(e.ins) == 52, 'the span decodes to 52 instructions'
for a, mn, ops, und, vis in e.undefined_report():
    print(f'UNDEF {a:04X} {mn} {ops}: {und} -> {vis if vis else "never observed (overwritten on every path)"}')
cases = '\n'.join(e.cases())

