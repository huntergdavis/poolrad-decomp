source = '''/* GAME.OVR unit 38h +0775 (009E slot 22), raw CPU on flat RAM (docs/re/OVL_0038_0775_CPU.md).
 * One case per original instruction; operands are reread from RAM in source order. Generated by
 * tools/overlay/emit_ovl038_0775.py; the +07AB stop and the +07C2 stub hop are that script's two hand-written cases. */
#include "poolrad/recovered/overlay_u38_handler_0775_cpu.h"
#include <string.h>
#define RAM_SIZE ((size_t)1u << 20)
#define MASK (RAM_SIZE - 1u)
#define STATUS(s) PR_U38_0775_##s
typedef pr_u38_0775_status pr_status_t;
typedef pr_u38_0775_cpu pr_cpu_t;
typedef struct {
    const pr_u38_0775_limits *limits;
    pr_u38_0775_diagnostic *diag;
} pr_run;
_Static_assert(sizeof(pr_cpu_t) == sizeof(pr_res_2199_cpu), "CPU layout (2199)");
_Static_assert(sizeof(pr_cpu_t) == sizeof(pr_system_leaf_cpu), "CPU layout (SYSTEM leaf)");
_Static_assert(sizeof(pr_cpu_t) == sizeof(pr_u9e_0026_cpu), "CPU layout (U9E 0026)");
static size_t physical(uint16_t seg, uint16_t off) { return (((size_t)seg << 4u) + off) & MASK; }
static uint16_t word_at(uint8_t *b, size_t at) { return (uint16_t)(b[at] | ((uint16_t)b[(at + 1u) & MASK] << 8u)); }
static uint8_t rd8(uint8_t *b, uint16_t seg, uint16_t off) { return b[physical(seg, off)]; }
static uint16_t rd16(uint8_t *b, uint16_t seg, uint16_t off) { return word_at(b, physical(seg, off)); }
static void wr8(uint8_t *b, uint16_t seg, uint16_t off, uint8_t v) { b[physical(seg, off)] = v; }
static void wr16(uint8_t *b, uint16_t seg, uint16_t off, uint16_t v)
{
    size_t at = physical(seg, off);
    b[at] = (uint8_t)v; b[(at + 1u) & MASK] = (uint8_t)(v >> 8u);
}
static void push(uint8_t *b, pr_cpu_t *c, uint16_t v) { c->sp = (uint16_t)(c->sp - 2u); wr16(b, c->ss, c->sp, v); }
static uint16_t pop(uint8_t *b, pr_cpu_t *c) { uint16_t v = rd16(b, c->ss, c->sp); c->sp = (uint16_t)(c->sp + 2u); return v; }
static void szp(pr_cpu_t *c, uint16_t r, unsigned bits)
{
    uint8_t p = (uint8_t)r;
    p ^= (uint8_t)(p >> 4u); p ^= (uint8_t)(p >> 2u); p ^= (uint8_t)(p >> 1u);
    if ((p & 1u) == 0u) c->flags |= 0x04u;
    if ((r & (bits == 8u ? 0xFFu : 0xFFFFu)) == 0u) c->flags |= 0x40u;
    if (r & (bits == 8u ? 0x80u : 0x8000u)) c->flags |= 0x80u;
}
static uint16_t arith(pr_cpu_t *c, uint16_t l, uint16_t r, unsigned carry, unsigned bits, unsigned sub)
{
    uint32_t mask = bits == 8u ? 0xFFu : 0xFFFFu, sign = bits == 8u ? 0x80u : 0x8000u;
    uint32_t wide = sub ? (uint32_t)l - r - carry : (uint32_t)l + r + carry;
    uint16_t res = (uint16_t)(wide & mask);
    c->flags &= (uint16_t)~0x08D5u;
    if (sub ? (uint32_t)l < (uint32_t)r + carry : wide > mask) c->flags |= 1u;
    if ((l ^ r ^ res) & 0x10u) c->flags |= 0x10u;
    if ((sub ? (l ^ r) & (l ^ res) : (uint16_t)~(l ^ r) & (l ^ res)) & sign) c->flags |= 0x800u;
    szp(c, res, bits); return res;
}
static uint16_t logic(pr_cpu_t *c, uint16_t v, unsigned bits)
{
    v = (uint16_t)(v & (bits == 8u ? 0xFFu : 0xFFFFu)); c->flags &= (uint16_t)~0x08D5u; szp(c, v, bits); return v;
}
/* 00BA:2199, the credited sidecar lookup, on the same RAM. LIMIT (a cyclic list without the key) stops here. */
static int call_sidecar_lookup_2199(uint8_t *b, pr_cpu_t *c, pr_run *r)
{
    pr_res_2199_cpu in; int s;
    memcpy(&in, c, sizeof in);
    s = (int)pr_res_00ba_2199_cpu(b, RAM_SIZE, &in, r->limits->lookup_loopbacks);
    memcpy(c, &in, sizeof in);
    r->diag->callee = 1; r->diag->callee_status = s; r->diag->site = 0x0789u;
    return s == PR_RES_2199_OK ? 0 : STATUS(CALLEE);
}
/* 0AF8:0B0B, SYSTEM StrLoad (string copy), on the same RAM. */
static int call_strload_0b0b(uint8_t *b, pr_cpu_t *c, pr_run *r)
{
    pr_system_leaf_cpu in; int s;
    memcpy(&in, c, sizeof in);
    s = (int)pr_system_strload_0b0b(b, RAM_SIZE, &in);
    memcpy(c, &in, sizeof in);
    r->diag->callee = 2; r->diag->callee_status = s; r->diag->site = 0x07A5u;
    return s == PR_SYSTEM_LEAF_RETURNED ? 0 : STATUS(CALLEE);
}
/* Unit 9E +0026 (list-node removal, a partial chain with its own stops), entered through the loaded stub's far JMP. */
static int call_u9e_list_release_0026(uint8_t *b, pr_cpu_t *c, pr_run *r)
{
    pr_u9e_0026_cpu in; int s;
    memcpy(&in, c, sizeof in);
    s = (int)pr_u9e_list_release_0026_cpu(b, RAM_SIZE, &in, &r->limits->release, &r->diag->d0026);
    memcpy(c, &in, sizeof in);
    r->diag->callee = 3; r->diag->callee_status = s; r->diag->site = 0x07C2u;
    return s == PR_U9E_0026_OK ? 0 : STATUS(CALLEE);
}

pr_u38_0775_status pr_u38_handler_0775_cpu(uint8_t *b, size_t ram_size, pr_u38_0775_cpu *c,
                                           const pr_u38_0775_limits *limits, pr_u38_0775_diagnostic *diagnostic)
{
    pr_run run, *dg = &run;
    pr_u38_0775_diagnostic local;
    uint16_t caller;
    if (b == NULL || c == NULL || limits == NULL || ram_size != RAM_SIZE || c->ip != 0x0775u)
        return STATUS(ARGUMENT);
    run.limits = limits; run.diag = diagnostic != NULL ? diagnostic : &local;
    memset(run.diag, 0, sizeof *run.diag);
    run.diag->callee = -1; run.diag->callee_status = -1; run.diag->d0026.freemem_status = -1;
    caller = c->cs;
    for (;;) {
        switch (c->ip) {
CASES
        default: return STATUS(TRANSFER);
        }
    }
}
'''.replace('CASES', cases)
targets = {ROOT / 'include/poolrad/recovered/overlay_u38_handler_0775_cpu.h': header,
           ROOT / 'src/recovered/overlay_u38_handler_0775_cpu.c': source}
if '--check' in sys.argv:
    bad = [str(p) for p, text in targets.items() if p.read_text() != text]
    print('EMIT_CHECK', 'MISMATCH ' + ', '.join(bad) if bad else 'OK'); sys.exit(1 if bad else 0)
for p, text in targets.items():
    p.write_text(text)
print('cases', len(e.ins))
