"""Source-only U19 join of independently validated same-run witnesses.

Call the existing route, host-event, passive-snapshot, and expected-RGB
producers first. This adapter checks their shared identity and shape; it does
not replay the guest, compare observed pixels, or attribute a plane write.
"""

from dataclasses import dataclass
from hashlib import sha256
import re
from typing import Protocol

from tools.replay.cold_start_codeword_row14_route_join import RouteGate
from tools.replay.cold_start_codeword_row14_target_filter import NEXT_PC


SHA256 = re.compile(r"[0-9a-f]{64}\Z")
TOKEN = re.compile(r"[A-Za-z0-9_-]{1,64}\Z")
HOST_WIDTH = 640
HOST_HEIGHT = 400
CROP_X = 16
CROP_Y = 224
CROP_WIDTH = 576
CROP_HEIGHT = 16
CROP_STRIDE = CROP_WIDTH * 3
CROP_BYTES = CROP_STRIDE * CROP_HEIGHT
JOIN_KEY_FIELDS = ("run_token", "plane_event_id", "arm_token", "store_ordinal")
GUEST_ORDER = ("printer_call", "selected_store", "store_successor",
               "printer_return")
HOST_ORDER = ("crtc_sample", "latch_enter", "latch_assign",
              "renderer_start", "renderer_end", "backend_complete",
              "rgb_capture")


class HostWitness(Protocol):
    """Result of p5's ordered correlate_selected event gate."""

    run: str
    plane_event_id: str
    arm_token: str
    store_ordinal: int
    drawer_offset: int
    frame: int
    real_start: int
    same_page: bool
    backend: str
    backend_event_id: str
    rgb_sha256: str
    palette_sha256: str
    palette_generation: int
    rgb_width: int
    rgb_height: int


class PassiveSnapshot(Protocol):
    """Result of pR's validate_capture, never unchecked capture JSON."""

    run_token: str
    plane_event_id: str
    arm_token: str
    store_ordinal: int
    site: int
    successor: int
    backing_index: int
    before_planes: bytes
    after_planes: bytes


@dataclass(frozen=True)
class ExpectedRgbPatch:
    """Private RGB24 bytes generated by p9's 36-cell U19 C producer."""

    rgb24: bytes
    source_sha256: str
    font_sha256: str
    cell_count: int = 36
    source_pixel_count: int = 2304
    x: int = CROP_X
    y: int = CROP_Y
    width: int = CROP_WIDTH
    height: int = CROP_HEIGHT
    row_stride: int = CROP_STRIDE


@dataclass(frozen=True)
class SourceJoin:
    run_token: str
    plane_event_id: str
    arm_token: str
    store_ordinal: int
    site: int
    successor: int
    backing_index: int
    frame: int
    backend_event_id: str
    rgb_sha256: str
    palette_sha256: str
    expected_crop_sha256: str
    same_page: bool
    status: str = "SOURCE_ONLY_JOIN_NO_PIXEL_OR_WRITE_ASSERTION"


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def _digest(value: object) -> bool:
    return isinstance(value, str) and SHA256.fullmatch(value) is not None


def join_source_contract(route: RouteGate, host: HostWitness,
                         plane: PassiveSnapshot,
                         expected: ExpectedRgbPatch) -> SourceJoin:
    """Join keys after each producer validates its own observation.

    Guest route frame indices and host event indices are separate clocks. The
    shared run token and selected-store event key bind their results; producer
    validators retain responsibility for each stream's chronological order.
    """
    route_token = route.run_token
    _require(isinstance(route_token, str) and TOKEN.fullmatch(route_token) is not None,
             "invalid route run token")
    selected = route.event.selected
    _require(selected.status == "PAIRED_CPU_SOURCE_ONLY" and
             type(selected.candidate_hits) is int and
             1 <= selected.candidate_hits <= 128 and
             type(route.selected_frame_index) is int and
             route.selected_frame_index >= 0 and
             selected.target_pc in NEXT_PC and
             selected.next_pc == NEXT_PC[selected.target_pc],
             "validated U19 selected-store route required")
    _require(route.event.change.sequence == 1 and
             route.event.change.pc == f"0F2D:{selected.target_pc:04X}",
             "route plane event differs from selected store")
    _require(host.run == route_token == plane.run_token and
             isinstance(host.plane_event_id, str) and
             TOKEN.fullmatch(host.plane_event_id) is not None and
             isinstance(host.arm_token, str) and
             bool(host.arm_token) and
             host.plane_event_id == plane.plane_event_id and
             host.arm_token == plane.arm_token and
             type(host.store_ordinal) is int and
             host.store_ordinal == plane.store_ordinal == selected.candidate_hits,
             "same-run selected-store key differs")
    _require(host.drawer_offset == plane.site == selected.target_pc and
             plane.successor == selected.next_pc,
             "drawer store/successor address differs")
    _require(type(plane.backing_index) is int and plane.backing_index >= 0 and
             isinstance(plane.before_planes, bytes) and
             isinstance(plane.after_planes, bytes) and
             len(plane.before_planes) == len(plane.after_planes) == 4,
             "validated passive four-plane snapshot required")
    _require(type(host.frame) is int and host.frame >= 0 and
             type(host.real_start) is int and host.real_start >= 0 and
             type(host.same_page) is bool and
             isinstance(host.backend, str) and bool(host.backend) and
             isinstance(host.backend_event_id, str) and bool(host.backend_event_id) and
             _digest(host.rgb_sha256) and _digest(host.palette_sha256) and
             type(host.palette_generation) is int and host.palette_generation >= 0 and
             (host.rgb_width, host.rgb_height) == (HOST_WIDTH, HOST_HEIGHT),
             "validated canonical host RGB event required")
    _require(isinstance(expected.rgb24, bytes) and
             len(expected.rgb24) == CROP_BYTES and
             (expected.cell_count, expected.source_pixel_count) == (36, 2304) and
             (expected.x, expected.y, expected.width, expected.height,
              expected.row_stride) ==
             (CROP_X, CROP_Y, CROP_WIDTH, CROP_HEIGHT, CROP_STRIDE) and
             _digest(expected.source_sha256) and _digest(expected.font_sha256),
             "p9 U19 expected RGB24 patch shape or provenance differs")
    return SourceJoin(route_token, host.plane_event_id, host.arm_token,
                      host.store_ordinal,
                      selected.target_pc, selected.next_pc,
                      plane.backing_index, host.frame, host.backend_event_id,
                      host.rgb_sha256, host.palette_sha256,
                      sha256(expected.rgb24).hexdigest(), host.same_page)
